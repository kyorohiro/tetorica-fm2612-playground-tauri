#!/usr/bin/env python3
"""Snapshot the shared C DSP as instance-owned C++ members without changing DSP.

Only storage/prototype syntax changes: static state becomes rack members, names
are scoped to each source file, C compound literals/calloc get C++ equivalents.
The checked hashes tie each generated member file to the upstream implementation.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

FILES = ("gain", "eq", "noise_gate", "compressor", "reverb", "extra_fx", "graph")
RENAMES = {
    "gain": ("State", "instances", "state", "input", "output"),
    "eq": ("State", "instances", "state"),
    "noise_gate": ("State", "instances", "state"),
    "compressor": ("State", "instances", "state"),
    "reverb": ("State", "instances", "state"),
    "extra_fx": ("states", "sr", "smoothing", "defaults"),
    "graph": ("draft", "active", "count", "active_count", "root"),
}


def transform(name, source):
    source = re.sub(r'^#include[^\n]*\n', '', source, flags=re.M)
    if name == "graph":
        # Sibling definitions are members of the enclosing C++ rack.
        source = re.sub(r'^#define DECLARE[^\n]*\n', '', source, flags=re.M)
        source = re.sub(r'^DECLARE[^\n]*\n', '', source, flags=re.M)
    source = re.sub(r'^.*\b(?:void|int|float)\s*\*?\s*\w+\([^{}]*\);[^\n]*\n', '', source, flags=re.M)
    source = re.sub(r'\bstatic\s+', '', source)
    for token in RENAMES[name]:
        suffix = '_storage' if name == 'gain' and token in ('input', 'output') else ''
        source = re.sub(r'\b' + token + r'\b', name + '_' + token + suffix, source)
    source = source.replace('(Biquad){0}', 'Biquad{}')
    source = source.replace('(Node){.type=type,.slot=slot}', 'Node{type,slot,0,{}}')
    source = source.replace('f->delay=calloc(', 'f->delay=(float *)calloc(')
    macros = re.findall(r'^#define (\w+)', source, flags=re.M)
    return '// Generated by scripts/sync_native_genesis_fx.py; do not edit.\n' + source + ''.join('\n#undef ' + m for m in macros) + '\n'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--source', type=Path, help='optional hello_ymfm comparison; offline --check uses the pinned input')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    out = Path(__file__).resolve().parents[1] / 'src-tauri' / 'native-fx'
    source = args.source or (out / 'snapshot' if args.check else Path(__file__).resolve().parents[3])
    hashes = {}
    expected = {}
    for name in FILES:
        relative = 'native/audio_effect/' + name + '.c'
        raw = (source / relative).read_bytes()
        hashes[relative] = hashlib.sha256(raw).hexdigest()
        expected[name + '.inc'] = transform(name, raw.decode()).encode()
        expected['snapshot/' + relative] = raw
    generated_hashes = {name: hashlib.sha256(data).hexdigest() for name, data in expected.items() if name.endswith('.inc')}
    expected['sources.json'] = (json.dumps({'source': 'hello_ymfm', 'sha256': hashes,
        'generated_sha256': generated_hashes}, indent=2) + '\n').encode()
    for name, data in expected.items():
        path = out / name
        if args.check:
            if not path.exists() or path.read_bytes() != data:
                raise SystemExit('Native FX snapshot differs: ' + str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print('Native FX snapshot: ' + ('verified' if args.check else 'updated'))


if __name__ == '__main__':
    main()
