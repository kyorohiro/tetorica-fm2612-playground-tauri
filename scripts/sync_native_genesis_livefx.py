#!/usr/bin/env python3
"""Pin the offline QuickJS-NG prototype and snapshot the shared LiveFX rack.

Normal checks/builds are offline. --fetch explicitly downloads the pinned
official release, verifies it, and updates only the named vendored files.
"""
import argparse
import hashlib
import io
import json
from pathlib import Path
import urllib.request
import zipfile

VERSION = 'v0.17.0'
COMMIT = '6d46d07d04041b40f4f49eaa7fdebe44c314c699'
ARCHIVE_URL = f'https://github.com/quickjs-ng/quickjs/releases/download/{VERSION}/quickjs-amalgam.zip'
ARCHIVE_SHA256 = 'a0955463c74809173a253ff87365095e6972e8b171cfb6aa8a1e781adf35cfeb'
LICENSE_URL = f'https://raw.githubusercontent.com/quickjs-ng/quickjs/{COMMIT}/LICENSE'
FILES = {'quickjs-amalgam.c', 'quickjs.h', 'LICENSE'}


def sha(data):
    return hashlib.sha256(data).hexdigest()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--source', type=Path, help='optional hello_ymfm comparison; offline --check uses the pinned input')
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--fetch', action='store_true')
    args = parser.parse_args()
    if args.check and args.fetch:
        parser.error('--check and --fetch are mutually exclusive')
    output = Path(__file__).resolve().parents[1] / 'src-tauri/native-livefx'
    vendor = output / 'quickjs-ng'
    if args.fetch:
        data = urllib.request.urlopen(ARCHIVE_URL, timeout=60).read()
        if sha(data) != ARCHIVE_SHA256:
            raise SystemExit('QuickJS-NG release archive hash mismatch')
        archive = zipfile.ZipFile(io.BytesIO(data))
        vendor.mkdir(parents=True, exist_ok=True)
        for name in FILES - {'LICENSE'}:
            (vendor / name).write_bytes(archive.read(name))
        (vendor / 'LICENSE').write_bytes(urllib.request.urlopen(LICENSE_URL, timeout=60).read())
    origin = args.source or (output / 'snapshot' if args.check else Path(__file__).resolve().parents[3])
    raw = (origin / 'web/custom_fx.js').read_bytes()
    source = raw.decode()
    if source.count('export class LiveFX') != 1:
        raise SystemExit('Unexpected shared LiveFX export shape')
    source = source.replace('export class LiveFX', 'class LiveFX', 1)
    # A C string literal preserves the source exactly, apart from the one export.
    generated = '// Generated by scripts/sync_native_genesis_livefx.py; do not edit.\n'
    generated += 'static const char native_livefx_source[] =\n'
    generated += '\n'.join(json.dumps(line + '\n', ensure_ascii=True).replace('?', r'\?') for line in source.splitlines()) + ';\n'
    context_raw = (origin / 'web/native_livefx_context.js').read_bytes()
    context_source = context_raw.decode().replace('export function ', 'function ')
    context_generated = '// Generated by scripts/sync_native_genesis_livefx.py; do not edit.\n'
    context_generated += 'static const char native_livefx_context_source[] =\n'
    context_generated += '\n'.join(json.dumps(line + '\n', ensure_ascii=True).replace('?', r'\?') for line in context_source.splitlines()) + ';\n'
    manifest = {
        'source': 'https://github.com/quickjs-ng/quickjs', 'tag': VERSION,
        'commit': COMMIT, 'archive_url': ARCHIVE_URL, 'archive_sha256': ARCHIVE_SHA256,
        'license_url': LICENSE_URL,
        'sha256': {name: sha((vendor / name).read_bytes()) for name in sorted(FILES)},
        'shared_sha256': {'web/custom_fx.js': sha(raw), 'web/native_livefx_context.js': sha(context_raw)},
        'generated_sha256': {'custom_fx.inc': sha(generated.encode()), 'context.inc': sha(context_generated.encode())},
        'transformation': 'Replace the sole export class LiveFX with class LiveFX; C-string encode without modifying rack behavior.',
    }
    for name, content in {'custom_fx.inc': generated.encode(), 'context.inc': context_generated.encode(),
            'snapshot/web/custom_fx.js': raw, 'snapshot/web/native_livefx_context.js': context_raw,
            'sources.json': (json.dumps(manifest, indent=2) + '\n').encode()}.items():
        target = output / name
        if args.check:
            if not target.exists() or target.read_bytes() != content:
                raise SystemExit('Native LiveFX snapshot differs: ' + str(target))
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(content)
    print('Native LiveFX snapshot: ' + ('verified' if args.check else 'updated'))


if __name__ == '__main__':
    main()
