#!/usr/bin/env python3
"""Snapshot the shared C noise implementation as per-renderer C++ state."""
import argparse
import hashlib
import json
from pathlib import Path
import re


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--source', type=Path, default=Path(__file__).resolve().parents[3])
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = args.source.resolve() / 'native/audio_effect/noise.c'
    raw = path.read_bytes()
    source = raw.decode()
    source = re.sub(r'^#include[^\n]*\n', '', source, flags=re.M)
    source = re.sub(r'^extern[^\n]*\n', '', source, flags=re.M)
    source = re.sub(r'\bstatic\s+', '', source)
    macros = re.findall(r'^#define (\w+)', source, flags=re.M)
    generated = '// Generated by scripts/sync_native_genesis_noise.py; do not edit.\n' + source + ''.join('\n#undef ' + macro for macro in macros) + '\n'
    expected = {
        'noise.inc': generated,
        'sources.json': json.dumps({'source': 'hello_ymfm', 'sha256': {'native/audio_effect/noise.c': hashlib.sha256(raw).hexdigest()}}, indent=2) + '\n',
    }
    output = Path(__file__).resolve().parents[1] / 'src-tauri/native-noise'
    for name, text in expected.items():
        target = output / name
        if args.check:
            if not target.exists() or target.read_text() != text:
                raise SystemExit('Native noise snapshot differs: ' + str(target))
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text)
    print('Native noise snapshot: ' + ('verified' if args.check else 'updated'))


if __name__ == '__main__':
    main()
